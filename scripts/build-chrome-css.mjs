/**
 * Extract header/footer/chrome tokens from home.css into a lean css/chrome.css
 * for landing pages that don't need the full homepage stylesheet (~93KB).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const home = fs.readFileSync(path.join(root, "css/home.css"), "utf8").split(/\r?\n/);

/** 1-based inclusive line ranges from home.css */
const ranges = [
  [1, 50], // tokens + site-root
  [414, 426], // .nav-toggle base
  [2003, 2435], // figma container + header + hamburger bars
  [2642, 2663], // figma-hero__pill
  [4274, 4643], // figma footer + mobile nav extras
];

const parts = [
  "/* Auto-generated by scripts/build-chrome-css.mjs — do not edit by hand */",
  "/* Lean header/footer/chrome extracted from home.css for landing pages */",
  "",
];

for (const [start, end] of ranges) {
  parts.push(`/* --- home.css L${start}-${end} --- */`);
  parts.push(...home.slice(start - 1, end));
  parts.push("");
}

const out = path.join(root, "css/chrome.css");
fs.writeFileSync(out, parts.join("\n"), "utf8");
console.log(
  "Wrote",
  out,
  `(${fs.statSync(out).size} bytes; home.css was ${fs.statSync(path.join(root, "css/home.css")).size})`
);
